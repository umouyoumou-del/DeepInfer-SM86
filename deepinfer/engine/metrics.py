"""Small dependency-free Prometheus metrics registry.

The gateway runs in a single Python process and does not need the full
``prometheus_client`` dependency for local operation.  Counters, gauges and
latency summaries are kept in thread-safe dictionaries and rendered in the
Prometheus text exposition format by :meth:`EngineMetrics.render`.
"""

from __future__ import annotations

import math
import threading
import time
from collections import defaultdict
from typing import Any

_HELP = {
    "requests_total": "Generation requests accepted by the engine.",
    "requests_finished_total": "Generation requests completed successfully.",
    "requests_failed_total": "Generation requests that failed or were cancelled.",
    "prompt_tokens_total": "Prompt tokens processed by the engine.",
    "generated_tokens_total": "Decode tokens generated by the engine.",
    "prefix_reused_tokens_total": "Prompt tokens served from the KV prefix cache.",
    "prefill_seconds_sum": "Cumulative prefill latency in seconds.",
    "decode_step_seconds_sum": "Cumulative decode-step latency in seconds.",
    "decode_steps_total": "Number of batched decode steps.",
    "up": "Whether the engine process is running.",
    "running_requests": "Requests currently in the decode loop.",
    "queued_requests": "Requests waiting for admission.",
    "kv_cache_blocks_used": "KV cache blocks referenced by requests or prefixes.",
    "kv_cache_blocks_free": "KV cache blocks available for allocation.",
    "kv_cache_blocks_total": "Total physical KV cache blocks.",
}


class EngineMetrics:
    """Thread-safe counters, gauges and summaries for one engine instance."""

    def __init__(self) -> None:
        self._lock = threading.RLock()
        self._counters: dict[str, float] = defaultdict(float)
        self._gauges: dict[str, float] = {"up": 1.0}
        self._summary_sum: dict[str, float] = defaultdict(float)
        self._summary_count: dict[str, int] = defaultdict(int)
        self.started_at = time.time()

    def inc(self, name: str, value: float = 1.0) -> None:
        with self._lock:
            self._counters[name] += float(value)

    def set_gauge(self, name: str, value: float) -> None:
        with self._lock:
            self._gauges[name] = float(value)

    def observe(self, name: str, value: float) -> None:
        with self._lock:
            self._summary_sum[name] += float(value)
            self._summary_count[name] += 1

    def get(self, name: str, default: float = 0.0) -> float:
        with self._lock:
            return self._counters.get(name, self._gauges.get(name, default))

    def snapshot(self) -> dict[str, Any]:
        with self._lock:
            counters = dict(self._counters)
            gauges = dict(self._gauges)
            summaries = {
                name: {
                    "sum": self._summary_sum[name],
                    "count": self._summary_count[name],
                    "avg": (
                        self._summary_sum[name] / self._summary_count[name]
                        if self._summary_count[name]
                        else 0.0
                    ),
                }
                for name in self._summary_sum
            }
            finished = counters.get("requests_finished_total", 0.0)
            failed = counters.get("requests_failed_total", 0.0)
            generated = counters.get("generated_tokens_total", 0.0)
            decode_time = summaries.get("decode_step_seconds", {}).get("sum", 0.0)
            return {
                "uptime_seconds": round(time.time() - self.started_at, 3),
                "counters": counters,
                "gauges": gauges,
                "summaries": summaries,
                "requests_finished": finished,
                "requests_failed": failed,
                "generated_tokens": generated,
                "decode_tokens_per_second": (
                    round(generated / decode_time, 3) if decode_time > 0 else 0.0
                ),
            }

    def render(self) -> str:
        """Render counters, gauges and summary averages in Prometheus format."""
        with self._lock:
            counters = dict(self._counters)
            gauges = dict(self._gauges)
            summary_avg = {
                name: (self._summary_sum[name] / self._summary_count[name])
                for name in self._summary_sum
                if self._summary_count[name]
            }
        lines: list[str] = []
        for name in sorted(counters):
            help_text = _HELP.get(name, f"DeepInfer SM86 metric {name}.")
            lines.append(f"# HELP deepinfer_{name} {help_text}")
            lines.append(f"# TYPE deepinfer_{name} counter")
            value = counters[name]
            if math.isfinite(value):
                lines.append(f"deepinfer_{name} {value:g}")
        for name in sorted(gauges):
            help_text = _HELP.get(name, f"DeepInfer SM86 gauge {name}.")
            lines.append(f"# HELP deepinfer_{name} {help_text}")
            lines.append(f"# TYPE deepinfer_{name} gauge")
            value = gauges[name]
            if math.isfinite(value):
                lines.append(f"deepinfer_{name} {value:g}")
        for name in sorted(summary_avg):
            help_text = _HELP.get(name, f"DeepInfer SM86 metric {name}.")
            lines.append(f"# HELP deepinfer_{name}_avg {help_text}")
            lines.append(f"# TYPE deepinfer_{name}_avg gauge")
            lines.append(f"deepinfer_{name}_avg {summary_avg[name]:g}")
        return "\n".join(lines) + "\n"


__all__ = ["EngineMetrics"]
